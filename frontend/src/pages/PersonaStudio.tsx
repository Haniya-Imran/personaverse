import { useState } from "react";
import { Banner, Claim, EmptyState, Orb, Spinner, ZBar } from "../components/ui";
import { api } from "../lib/api";
import { num, pct, segColor, segmentTitle } from "../lib/format";
import type { PersonaResult, Segment } from "../lib/types";
import { useWorkspace } from "../state/Workspace";

function personaText(p: PersonaResult, seg: Segment) {
  const q = p.persona;
  return [`${q.persona_name} — ${seg.size} customers (${pct(seg.share, 1)})`, q.segment_overview,
    `Marketing approach: ${q.marketing_approach}`, `Communication style: ${q.communication_style}`,
    `Suggested offers: ${q.suggested_offers.join("; ")}`, `(AI-generated by ${p.provider}/${p.model}; hypotheses are interpretations.)`].join("\n\n");
}

function ClaimList({ title, items }: { title: string; items: { text: string; basis: "observed" | "hypothesis" }[] }) {
  if (!items.length) return null;
  return (
    <div className="stack" style={{ gap: 8 }}>
      <h3>{title}</h3>
      <ul style={{ margin: 0, padding: 0, listStyle: "none", display: "flex", flexDirection: "column", gap: 8, fontSize: 14 }}>
        {items.map((c, i) => <Claim key={i} {...c} />)}
      </ul>
    </div>
  );
}

export default function PersonaStudio() {
  const ws = useWorkspace();
  const [inputView, setInputView] = useState<Record<number, unknown>>({});
  const [copied, setCopied] = useState(false);
  if (!ws.insights || !ws.analysis) return <EmptyState title="No segments yet" body="Personas are written from segment statistics, so run segmentation first." to="/app/segmentation" cta="Go to Segmentation" />;
  const segs = ws.insights.segments.filter((s) => !s.is_noise);
  const sel = segs.find((s) => s.id === ws.selectedSegment) ?? segs[0];
  const p = ws.personas[sel.id];
  const busy = !!ws.personaBusy[sel.id];
  const err = ws.personaErrors[sel.id];
  const llmOff = ws.llm && !ws.llm.configured;
  const anyPersona = Object.keys(ws.personas).length > 0;
  const genAll = async () => { for (const s of segs) if (!ws.personas[s.id]) await ws.generatePersona(s.id); };
  const showInput = async () => {
    if (inputView[sel.id]) { setInputView({ ...inputView, [sel.id]: undefined }); return; }
    setInputView({ ...inputView, [sel.id]: await api.personaInput(ws.analysis!.analysis_id, sel.id) });
  };

  return (
    <>
      <div className="between">
        <div>
          <span className="label">Module F · Persona intelligence studio</span>
          <h1 style={{ marginTop: 6 }}>{segs.length} segments, <span className="serif" style={{ color: "var(--accent-deep)" }}>{segs.length} personalities.</span></h1>
        </div>
        <div style={{ display: "flex", gap: 10, flexWrap: "wrap" }}>
          <button className="btn primary" onClick={genAll} disabled={!!llmOff || segs.every((s) => ws.personas[s.id]) || Object.values(ws.personaBusy).some(Boolean)}>Generate all personas</button>
          <a className="btn" href={anyPersona ? api.reportUrl(ws.analysis.analysis_id, "personas.md") : undefined} aria-disabled={!anyPersona} onClick={(e) => { if (!anyPersona) e.preventDefault(); }}>Export personas (.md)</a>
        </div>
      </div>

      {llmOff && (
        <Banner kind="warn">
          <b>AI personas are not configured on this server.</b> Set <span className="mono">GEMINI_API_KEY</span> (free tier works) or <span className="mono">OPENAI_API_KEY</span> in the backend environment and restart it.
          Segment statistics and recommendations below still work — they are calculated from the data and are clearly not AI-generated.
        </Banner>
      )}

      <div role="tablist" aria-label="Segments" style={{ display: "flex", flexWrap: "wrap", gap: 8 }}>
        {segs.map((s) => (
          <button key={s.id} role="tab" aria-selected={s.id === sel.id} className={`pill ${s.id === sel.id ? "on" : ""}`} onClick={() => ws.selectSegment(s.id)}>
            <span className="dot" style={{ background: segColor(s.id).color }} />{segmentTitle(s)}
            {ws.personas[s.id] && <span aria-label="persona ready">✓</span>}
          </button>
        ))}
      </div>

      <div className="row" style={{ alignItems: "flex-start" }}>
        <section className="card stack" style={{ flex: "2 1 560px" }} aria-live="polite">
          <div className="between">
            <span className="label">{p ? "AI persona" : "Segment"}</span>
            {p ? <span className="badge">LLM-generated · {p.provider} / {p.model}</span> : <span className="badge bad">Not AI-generated yet</span>}
          </div>
          <div style={{ display: "flex", alignItems: "center", gap: 16 }}>
            <Orb id={sel.id} size={68} />
            <div>
              <h2 style={{ fontSize: 26 }}>{p ? p.persona.persona_name : sel.statistical_name}</h2>
              <div className="muted" style={{ fontSize: 14 }}>Segment {sel.id} · {sel.size.toLocaleString()} customers · {pct(sel.share, 1)} of total</div>
            </div>
          </div>

          {busy && <div className="banner info"><Spinner label="Writing persona from this segment's statistics…" /></div>}
          {err && <Banner kind="error">{err}</Banner>}

          {p ? (
            <>
              <p className="serif" style={{ fontSize: 24, lineHeight: 1.3, margin: 0 }}>{p.persona.segment_overview}</p>
              <div className="banner warn" style={{ fontSize: 13 }}><span>Describes a group, not a real person. <b>Observed</b> items restate measured statistics; <b>Hypothesis</b> items are AI interpretations to test.</span></div>
              <div className="grid-auto" style={{ gridTemplateColumns: "repeat(auto-fit, minmax(min(100%, 280px), 1fr))", gap: 20 }}>
                <ClaimList title="Characteristics" items={p.persona.customer_characteristics} />
                <ClaimList title="Behaviour" items={p.persona.behavioral_patterns} />
                <ClaimList title="Needs and preferences" items={p.persona.needs_and_preferences} />
                <ClaimList title="Motivations" items={p.persona.motivations} />
                <ClaimList title="Pain points" items={p.persona.pain_points} />
                <ClaimList title="Product interests" items={p.persona.product_interests} />
              </div>
              {[["Purchasing habits", p.persona.purchasing_habits], ["Spending", p.persona.spending_behavior], ["Engagement", p.persona.engagement_patterns]]
                .filter(([, v]) => v).map(([t, v]) => <div key={t as string}><h3>{t}</h3><p className="body" style={{ margin: "4px 0 0", fontSize: 14 }}>{v}</p></div>)}
              <div className="dark-card stack" style={{ gap: 10 }}>
                <div className="label" style={{ color: "#AEB6C4" }}>How to reach them</div>
                <p style={{ margin: 0, color: "#E4E8EE" }}><b style={{ color: "#fff" }}>Approach:</b> {p.persona.marketing_approach}</p>
                <p style={{ margin: 0, color: "#E4E8EE" }}><b style={{ color: "#fff" }}>Tone:</b> {p.persona.communication_style}</p>
                <ul style={{ margin: 0, paddingLeft: 18, color: "#CDD3DC" }}>{p.persona.suggested_offers.map((o) => <li key={o}>{o}</li>)}</ul>
              </div>
              <div>
                <h3 style={{ marginBottom: 8 }}>Evidence behind this persona</h3>
                <div className="table-wrap"><table className="data">
                  <thead><tr><th>Claim</th><th>Feature</th><th>Statistic</th></tr></thead>
                  <tbody>{p.persona.evidence_summary.map((e, i) => <tr key={i}><td style={{ whiteSpace: "normal" }}>{e.claim}</td><td className="mono">{e.feature}</td><td style={{ whiteSpace: "normal" }}>{e.statistic}</td></tr>)}</tbody>
                </table></div>
              </div>
              <div style={{ display: "flex", gap: 10, flexWrap: "wrap" }}>
                <button className="btn" onClick={() => ws.generatePersona(sel.id, true)} disabled={busy}>Regenerate</button>
                <button className="btn" onClick={async () => { await navigator.clipboard.writeText(personaText(p, sel)); setCopied(true); setTimeout(() => setCopied(false), 1800); }}>{copied ? "Copied" : "Copy summary"}</button>
                <span className="muted" style={{ fontSize: 12, alignSelf: "center" }}>Generated {new Date(p.generated_at).toLocaleString()}{p.cached ? " · from cache" : ""}</span>
              </div>
            </>
          ) : (
            <>
              <div className="banner info" style={{ fontSize: 14 }}>
                <div><b>Statistical summary (calculated, not AI-generated):</b> {sel.statistical_name}. {sel.size.toLocaleString()} customers.</div>
              </div>
              <button className="btn primary" style={{ alignSelf: "flex-start" }} onClick={() => ws.generatePersona(sel.id)} disabled={busy || !!llmOff}>
                {busy ? "Generating…" : "Generate AI persona"}
              </button>
            </>
          )}
        </section>

        <aside className="stack" style={{ flex: "1 1 320px" }}>
          <section className="card stack">
            <h2>The numbers it is built on</h2>
            {sel.distinguishing.map((f) => (
              <div key={f.feature} style={{ fontSize: 13 }}>
                <div className="between"><span>{f.label}</span><span className="muted">{num(f.segment_mean)} vs {num(f.overall_mean)}</span></div>
                <ZBar z={f.z} />
              </div>
            ))}
            {sel.categorical.map((c) => <div key={c.feature} style={{ fontSize: 13 }}>{c.label}: most often <b>{c.top_value}</b> ({pct(c.segment_share)} vs {pct(c.overall_share)} overall)</div>)}
          </section>
          <section className="card stack">
            <h2>Privacy</h2>
            <p className="body" style={{ margin: 0, fontSize: 13 }}>Only averages, shares and differences for this segment are sent to the AI — never individual rows, IDs or personal columns.</p>
            <button className="btn small" onClick={showInput}>{inputView[sel.id] ? "Hide AI input" : "View exact AI input"}</button>
            {inputView[sel.id] != null && <pre className="well mono" style={{ fontSize: 11, padding: 12, maxHeight: 320, overflow: "auto", whiteSpace: "pre-wrap", margin: 0 }}>{JSON.stringify(inputView[sel.id], null, 1)}</pre>}
          </section>
        </aside>
      </div>
    </>
  );
}
