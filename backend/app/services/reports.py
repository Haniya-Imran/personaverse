"""Exports: segment statistics CSV, customer assignments CSV, persona Markdown and
a self-contained HTML business report (printable to PDF from any browser)."""
from __future__ import annotations

import html
import io

import pandas as pd

from .analysis import Analysis
from .intelligence import humanize


def segments_csv(a: Analysis) -> str:
    rows = []
    for s in a.insights["segments"]:
        row = {"segment_id": s["id"], "name": s["statistical_name"], "customers": s["size"],
               "share_pct": round(s["share"] * 100, 2)}
        for f in s["features"]:
            row[f"{f['feature']}_mean"] = round(f["segment_mean"], 3)
            row[f"{f['feature']}_z"] = f["z"]
        rows.append(row)
    return pd.DataFrame(rows).to_csv(index=False)


def assignments_csv(a: Analysis) -> str:
    df = a.dataset.data
    out = pd.DataFrame({"row": range(len(df))})
    if a.dataset.id_column:
        out[a.dataset.id_column] = df[a.dataset.id_column].values
    out["segment_id"] = a.model.labels
    names = {s["id"]: s["statistical_name"] for s in a.insights["segments"]}
    out["segment_name"] = [names[int(l)] for l in a.model.labels]
    for c in a.numeric + a.categorical:
        out[c] = df[c].values
    buf = io.StringIO()
    out.to_csv(buf, index=False)
    return buf.getvalue()


def persona_markdown(p: dict, seg: dict) -> str:
    q = p["persona"]
    lines = [f"# {q['persona_name']} (segment {seg['id']})", "",
             f"*{seg['size']} customers · {seg['share']:.1%} of total · generated by {p['provider']} / {p['model']} on {p['generated_at']}*",
             "", "> AI-generated persona describing a group, not a real person. Items marked (hypothesis) are interpretations, not measurements.",
             "", q["segment_overview"], ""]

    def claims(title, items):
        if items:
            lines.append(f"## {title}")
            lines.extend(f"- {c['text']}" + (" *(hypothesis)*" if c["basis"] == "hypothesis" else "") for c in items)
            lines.append("")

    claims("Characteristics", q["customer_characteristics"])
    claims("Behaviour", q["behavioral_patterns"])
    for k, t in (("purchasing_habits", "Purchasing habits"), ("spending_behavior", "Spending"),
                 ("engagement_patterns", "Engagement")):
        if q.get(k):
            lines += [f"## {t}", q[k], ""]
    claims("Needs and preferences", q["needs_and_preferences"])
    claims("Motivations", q["motivations"])
    claims("Pain points", q["pain_points"])
    claims("Product interests", q["product_interests"])
    lines += ["## Marketing approach", q["marketing_approach"], "", "## Communication style", q["communication_style"], "",
              "## Suggested offers"] + [f"- {o}" for o in q["suggested_offers"]] + ["", "## Evidence"]
    lines += [f"- {e['claim']} — `{e['feature']}`: {e['statistic']}" for e in q["evidence_summary"]]
    return "\n".join(lines) + "\n"


def _e(x) -> str:
    return html.escape(str(x))


def report_html(analysis_id: str, a: Analysis, personas: dict[int, dict]) -> str:
    m, ins = a.metrics, a.insights
    seg_html = []
    for s in ins["segments"]:
        p = personas.get(s["id"])
        title = _e(p["persona"]["persona_name"]) if p else _e(s["statistical_name"])
        dist = "".join(f"<li>{_e(f['label'])}: {f['segment_mean']:,.2f} vs {f['overall_mean']:,.2f} ({f['z']:+.2f} SD)</li>"
                       for f in s["distinguishing"])
        recs = "".join(f"<li><b>{_e(r['title'])}</b> — {_e(r['action'])}<br><small>Why: {_e('; '.join(r['why']))}</small></li>"
                       for r in s["recommendations"])
        risks = "".join(f"<li>{_e(r)}</li>" for r in s["risks"]) or "<li>None flagged.</li>"
        persona_block = (f"<p><i>AI persona ({_e(p['provider'])} / {_e(p['model'])}):</i> {_e(p['persona']['segment_overview'])}</p>"
                         if p else "<p><i>No AI persona generated for this segment yet.</i></p>")
        seg_html.append(f"""<section><h2>Segment {s['id']}: {title}</h2>
<p><b>{s['size']:,}</b> customers · {s['share']:.1%} · statistical label: {_e(s['statistical_name'])}</p>
{persona_block}<h3>What makes it different</h3><ul>{dist}</ul>
<h3>Recommendations</h3><ul>{recs}</ul><h3>Risks</h3><ul>{risks}</ul></section>""")
    expl = "".join(f"<li>{_e(x)}</li>" for x in a.comparison["selection"]["explanation"])
    vr = ins.get("value_rank")
    value = (f"<p>Most valuable by <b>{_e(vr['metric'])}</b>: " + " → ".join(f"segment {i}" for i in vr["order"]) + "</p>") if vr else ""
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><title>PersonaVerse report {analysis_id}</title>
<style>body{{font-family:system-ui,sans-serif;max-width:900px;margin:40px auto;padding:0 20px;color:#1B2130;line-height:1.55}}
h1{{font-size:28px}}h2{{margin-top:36px;border-top:1px solid #ccd;padding-top:18px}}small{{color:#4B5468}}
table{{border-collapse:collapse}}td,th{{border:1px solid #ccd;padding:6px 10px;text-align:left}}</style></head><body>
<h1>Customer Segmentation Report</h1>
<p>Dataset: {_e(a.dataset.name)} · {len(a.dataset.data):,} customers · analysis {analysis_id} · {a.created_at}</p>
<h2>Method</h2><p>Features: {_e(', '.join(humanize(c) for c in a.numeric + a.categorical))}. Preprocessing: median/mode imputation,
1st–99th percentile capping, standard scaling, one-hot encoding.</p>
<table><tr><th>Algorithm</th><td>{_e(a.model.algorithm)} {_e(a.model.params)}</td></tr>
<tr><th>Segments</th><td>{m['n_clusters']}</td></tr><tr><th>Silhouette</th><td>{m['silhouette']}</td></tr>
<tr><th>Davies-Bouldin</th><td>{m['davies_bouldin']}</td></tr><tr><th>Calinski-Harabasz</th><td>{m['calinski_harabasz']}</td></tr>
<tr><th>Noise share</th><td>{m['noise_share']}</td></tr></table>
<h3>Why this model</h3><ul>{expl}</ul>{value}
<p><small>3D view: {_e(a.projection['method'])}, {a.projection['explained_total']:.0%} of variance in 3 axes (visual only).</small></p>
{''.join(seg_html)}
<p><small>Statistics are computed from the data. AI personas are interpretations of aggregate statistics and are labelled as such.
Generated by PersonaVerse. Print this page to save it as PDF.</small></p></body></html>"""
